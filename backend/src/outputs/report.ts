// Renders evaluation_report.md and model_card.md. Every number comes from the evidence object, which is
// computed in the same run; no figure is typed in. No timestamps, so equal input gives equal bytes.
import type { Metrics, Ratio } from '../modules/extraction/ai/evaluation.js';
import { DOC_TYPES } from '../modules/extraction/ai/validators.js';

export interface InputFile {
  file: string;
  sha256: string;
}

export interface Mismatch {
  applicationId: string;
  column: string;
  expected: string;
  actual: string;
}

export interface Evidence {
  inputs: InputFile[];
  extractorVersion: string;
  rulesEngineVersion: string;
  poorScanDefinition: string;
  sample: {
    documents: number;
    applications: number;
    declared: Metrics;
    keywordRule: Metrics;
    regexOnly: { label: string; metrics: Metrics };
    ai: { label: string; metrics: Metrics };
    mockVsExpected: { checked: number; mismatches: Mismatch[] };
    aiVsExpected: { checked: number; mismatches: Mismatch[]; applicationsDiffering: string[] };
    /** Worked example 9: the poor PAN scan, as read by the AI provider. */
    example9: {
      aiDecision: string;
      aiReasonCodes: string[];
      panValue: string | null;
      panConfidence: number | null;
      fieldsBelowThreshold: { docType: string; field: string; confidence: number }[];
    } | null;
  };
  evaluation: {
    applications: number;
    documents: number;
    mockDecisionCounts: Record<string, number>;
    aiDecisionCounts: Record<string, number>;
    aiVsMockDecisionAgreement: Ratio;
    docTypeAgreementWithMock: Ratio;
    fieldAgreementWithMock: Ratio; // mock rows with confidence >= threshold only
    injection: {
      docId: string;
      aiDocType: string;
      aiWarnings: string[];
      mockDocType: string;
      keywordRuleDocType: string;
      decisionWithAi: string;
      applicationId: string;
    } | null;
    nameMismatchMinorByGender: { gender: string; applications: number; mock: number; ai: number }[];
    lowConfidenceAiDocuments: number;
  };
  officerFeedback: { aiFieldsExtracted: number | null; officerCorrections: number | null };
  databaseVsFilesIdentical: boolean | null;
}

const pct = (r: Ratio): string =>
  r.rate === null ? 'n/a' : `${(r.rate * 100).toFixed(1)}% (${r.correct}/${r.total})`;
const table = (headers: string[], rows: string[][]): string =>
  [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');

function confusion(m: Metrics): string {
  const types = [...DOC_TYPES];
  return table(
    ['truth \\ predicted', ...types],
    types.map((t) => [t, ...types.map((p) => String(m.classification.confusion[t]?.[p] ?? 0))]),
  );
}

const FIELDS = [
  'name',
  'dob',
  'gender',
  'pan_number',
  'aadhaar_last4',
  'address',
  'pincode',
  'document_date',
  'valid_until',
];
const targetNote = (value: number | null, target: number): string =>
  value === null
    ? 'n/a'
    : value >= target
      ? `at or above the reference target (${(target * 100).toFixed(0)}%)`
      : `BELOW the reference target (${(target * 100).toFixed(0)}%)`;
const counts = (c: Record<string, number>): string =>
  Object.entries(c)
    .sort()
    .map(([k, v]) => `${k} ${v}`)
    .join(', ');

export function renderReport(e: Evidence): string {
  const s = e.sample;
  const ai = s.ai.metrics;
  const v1 = s.regexOnly.metrics;
  const lines: string[] = [];
  const p = (...x: string[]) => lines.push(...x);

  p(
    '# OnboardIQ - evaluation report',
    '',
    'Generated by `npm run outputs`. It contains no timestamps, so the same inputs, database state and configuration give the same file.',
    '',
    '## 1. Scope and how to read this',
    '',
    '- **Sample set** (178 documents with a truth file, 60 applications with expected decisions) is the only data with labels. All accuracy figures below are on it.',
    '- **The extractor was developed while looking at the sample documents.** Every sample figure is therefore a *development-set* result, not an estimate for unseen data. The truth file is used only to score predictions: no extractor receives it, and `declared_doc_type` is not an input to any classifier.',
    '- **Evaluation set** (100 applications, 296 documents, one prompt-injection document) has **no truth and no expected decisions**. Nothing about its correctness is claimed; section 7 reports only the evidence that exists without labels (agreement with the mock provider, distributions, the injection document).',
    '- **LLM-assisted variant: not evaluated.** The provider supports an optional LLM, but no API key was configured for this run, so no figure here involves a model. The deterministic rules are what was measured.',
    `- Scan quality: ${e.poorScanDefinition}`,
    '',
  );

  p(
    '## 2. Inputs',
    '',
    table(
      ['file', 'sha256'],
      e.inputs.map((i) => [`\`${i.file}\``, `\`${i.sha256}\``]),
    ),
    '',
    `Extractor under test: \`${e.extractorVersion}\`. Rules engine: ${e.rulesEngineVersion}.`,
    '',
  );

  p(
    '## 3. AI-1 document classification (sample, 178 documents)',
    '',
    table(
      ['classifier', 'accuracy', 'clean scans', 'poor scans'],
      [
        [
          'declared_doc_type (what the customer selected)',
          pct(s.declared.classification.overall),
          pct(s.declared.classification.clean),
          pct(s.declared.classification.poor),
        ],
        [
          'keyword rule (first keyword found)',
          pct(s.keywordRule.classification.overall),
          pct(s.keywordRule.classification.clean),
          pct(s.keywordRule.classification.poor),
        ],
        [
          '**weighted features + injection guard (AI provider)**',
          `**${pct(ai.classification.overall)}**`,
          pct(ai.classification.clean),
          pct(ai.classification.poor),
        ],
      ],
    ),
    '',
    `Reference target: accuracy of at least 97%. Measured: ${pct(ai.classification.overall)}, ${targetNote(ai.classification.overall.rate, 0.97)} (development set).`,
    '',
    '### Confusion matrix - AI provider',
    '',
    confusion(ai),
    '',
    '### Confusion matrix - keyword rule (baseline)',
    '',
    confusion(s.keywordRule),
    '',
  );

  p(
    '## 4. AI-2 field extraction (sample, exact match after normalisation)',
    '',
    'Name and address are compared upper case with spaces collapsed; every other field exactly. A field the extractor did not produce counts as wrong.',
    '',
    table(
      ['field', 'regex-only v1 overall', 'AI overall', 'AI clean', 'AI poor'],
      [
        ...FIELDS.map((f) => [
          f,
          pct(v1.fields.byField[f] ?? { correct: 0, total: 0, rate: null }),
          pct(ai.fields.byField[f] ?? { correct: 0, total: 0, rate: null }),
          pct(ai.fields.cleanByField[f] ?? { correct: 0, total: 0, rate: null }),
          pct(ai.fields.poorByField[f] ?? { correct: 0, total: 0, rate: null }),
        ]),
        [
          '**all fields**',
          pct(v1.fields.overall),
          `**${pct(ai.fields.overall)}**`,
          pct(ai.fields.clean),
          pct(ai.fields.poor),
        ],
      ],
    ),
    '',
    `Reference targets: at least 90% overall, and at least 98% for pan_number, aadhaar_last4 and dob on clean documents.`,
    '',
    `- Overall: ${pct(ai.fields.overall)}, ${targetNote(ai.fields.overall.rate, 0.9)}.`,
    ...['pan_number', 'aadhaar_last4', 'dob'].map(
      (f) =>
        `- ${f} on clean documents: ${pct(ai.fields.cleanByField[f] ?? { correct: 0, total: 0, rate: null })}, ${targetNote(ai.fields.cleanByField[f]?.rate ?? null, 0.98)}.`,
    ),
    `- Poor scans: ${pct(ai.fields.poor)} versus ${pct(v1.fields.poor)} for the regex-only first version. Names on poor scans are the weak point: see ${pct(ai.fields.poorByField.name ?? { correct: 0, total: 0, rate: null })}.`,
    '',
    'Every figure above is on the development set, so treat them as an upper bound.',
    '',
  );

  p(
    '## 5. AI-4 confidence calibration (sample)',
    '',
    table(
      ['', 'regex-only v1 (flat 0.90)', 'AI provider'],
      [
        [
          'precision of fields accepted at confidence >= 0.80',
          pct(v1.confidence.accepted),
          `**${pct(ai.confidence.accepted)}**`,
        ],
        [
          'share of all fields accepted at >= 0.80 (coverage)',
          pct(v1.confidence.coverage),
          pct(ai.confidence.coverage),
        ],
        [
          'accuracy of fields below 0.80 (sent to a person)',
          pct(v1.confidence.sentToReview),
          pct(ai.confidence.sentToReview),
        ],
        [
          'correct values that still went to a person',
          String(v1.confidence.correctSentToReview),
          String(ai.confidence.correctSentToReview),
        ],
        [
          'document types classified correctly when confidence >= 0.80',
          pct(v1.classification.accurateWhenConfident),
          pct(ai.classification.accurateWhenConfident),
        ],
      ],
    ),
    '',
    'A value that needed an OCR repair gets 0.70 and free text on a garbled scan 0.72, so those go to review even when they happen to be right; that is the conservative choice.',
    '',
    '### Officer correction rate',
    '',
    e.officerFeedback.aiFieldsExtracted === null
      ? 'Not available: this run read the supplied files only (no database).'
      : e.officerFeedback.aiFieldsExtracted === 0
        ? `Not available: the database holds **0** AI-extracted fields reviewed by officers (and ${e.officerFeedback.officerCorrections ?? 0} officer corrections), so a correction rate cannot be computed. The supplied data contains no officer feedback. Once officers work AI-extracted cases the rate is corrections / AI-extracted fields; corrections are stored as labelled feedback.`
        : `${e.officerFeedback.officerCorrections ?? 0} officer corrections over ${e.officerFeedback.aiFieldsExtracted} AI-extracted fields.`,
    '',
  );

  p(
    '## 6. Baseline comparison summary (sample)',
    '',
    table(
      ['', 'regex-only first version', 'AI provider'],
      [
        [
          'classification accuracy',
          `${pct(s.keywordRule.classification.overall)} (keyword rule)`,
          pct(ai.classification.overall),
        ],
        ['field exact-match, all documents', pct(v1.fields.overall), pct(ai.fields.overall)],
        ['field exact-match, poor scans', pct(v1.fields.poor), pct(ai.fields.poor)],
        [
          'precision of fields accepted at >= 0.80',
          pct(v1.confidence.accepted),
          pct(ai.confidence.accepted),
        ],
      ],
    ),
    '',
  );

  p(
    '## 7. Evaluation set (no labels): available evidence only',
    '',
    `${e.evaluation.applications} applications and ${e.evaluation.documents} documents. There are no expected decisions or truth values for this set, so none are invented and no accuracy is claimed.`,
    '',
    '### Decisions',
    '',
    table(
      ['source', 'APPROVE / REVIEW / REJECT'],
      [
        ['mock extraction (`decisions_output.csv`)', counts(e.evaluation.mockDecisionCounts)],
        ['AI extraction (`ai_decisions_output.csv`)', counts(e.evaluation.aiDecisionCounts)],
      ],
    ),
    '',
    `Review and reject shares are higher than in live traffic because the evaluation set is enriched with problem cases (spec section 4).`,
    '',
    '### Agreement of the AI provider with the supplied mock extraction',
    '',
    'The mock provider is a simulation, not ground truth: it contains realistic confident misreads. Agreement is therefore *not* accuracy.',
    '',
    table(
      ['measure', 'result'],
      [
        [
          'same decision from AI extraction and mock extraction',
          pct(e.evaluation.aiVsMockDecisionAgreement),
        ],
        ['same document type as the mock', pct(e.evaluation.docTypeAgreementWithMock)],
        [
          'same value for the mock rows with confidence >= 0.80',
          pct(e.evaluation.fieldAgreementWithMock),
        ],
        [
          'AI documents with doc_type confidence below 0.80',
          String(e.evaluation.lowConfidenceAiDocuments),
        ],
      ],
    ),
    '',
    "Most disagreements in field values were checked by hand and are the mock provider's own confident digit/letter misreads (for example `Flat I5`, `8engaluru`, `Temple 5treet`), where the AI value is the plausible one; this cannot be proven without truth.",
    'During development a first agreement check on these documents gave 1,229 of 1,259 mock fields (97.6%) before a handful of generic parsing gaps it exposed were fixed. The figure in the table is after those fixes, so it is no longer an independent measurement.',
    '',
  );

  if (e.evaluation.injection) {
    const i = e.evaluation.injection;
    p(
      '### Prompt-injection document',
      '',
      table(
        ['', 'result'],
        [
          ['document', `\`${i.docId}\` (application \`${i.applicationId}\`)`],
          ['plain keyword rule (baseline)', i.keywordRuleDocType],
          ['mock provider', i.mockDocType],
          ['AI provider', `${i.aiDocType} (warnings: ${i.aiWarnings.join(', ') || 'none'})`],
          ['decision for the application with AI extraction', i.decisionWithAi],
        ],
      ),
      '',
      'The document text is never followed: instruction-like lines are removed before classification and extraction, the document is flagged, and it is classified OTHER. It reaches the decision only as a document of type OTHER, which the rules treat like any other unrecognised document.',
      '',
    );
  }

  p(
    '### Fairness check: NAME_MISMATCH_MINOR by gender (evaluation set)',
    '',
    table(
      ['gender', 'applications', 'mock extraction', 'AI extraction'],
      e.evaluation.nameMismatchMinorByGender.map((g) => [
        g.gender,
        String(g.applications),
        `${g.mock} (${g.applications ? ((g.mock / g.applications) * 100).toFixed(1) : '0.0'}%)`,
        `${g.ai} (${g.applications ? ((g.ai / g.applications) * 100).toFixed(1) : '0.0'}%)`,
      ]),
    ),
    '',
    'Counts are small; this is a monitoring figure, not a statistical test. Name matching uses one normalisation for everyone (titles removed, token order ignored).',
    '',
  );

  p(
    '## 8. End-to-end decisions on the sample (the only place decisions can be checked)',
    '',
    table(
      [
        'extraction used',
        'applications matching all five expected columns',
        'applications differing',
      ],
      [
        [
          'mock (supplied extraction_mock)',
          `${s.mockVsExpected.checked - new Set(s.mockVsExpected.mismatches.map((m) => m.applicationId)).size}/${s.mockVsExpected.checked}`,
          String(new Set(s.mockVsExpected.mismatches.map((m) => m.applicationId)).size),
        ],
        [
          'AI provider',
          `${s.aiVsExpected.checked - s.aiVsExpected.applicationsDiffering.length}/${s.aiVsExpected.checked}`,
          String(s.aiVsExpected.applicationsDiffering.length),
        ],
      ],
    ),
    '',
    s.aiVsExpected.applicationsDiffering.length === 0
      ? 'The AI extraction reproduces every expected decision.'
      : `Applications where AI extraction gives a different result from the expected columns (the expected columns assume the mock extraction): ${s.aiVsExpected.applicationsDiffering.map((a) => `\`${a}\``).join(', ')}.`,
    '',
    ...(s.aiVsExpected.mismatches.length
      ? [
          table(
            ['application', 'column', 'expected', 'AI result'],
            s.aiVsExpected.mismatches
              .slice(0, 40)
              .map((m) => [
                m.applicationId,
                m.column,
                m.expected || '(empty)',
                m.actual || '(empty)',
              ]),
          ),
          '',
        ]
      : []),
    ...example9Paragraph(s.example9, ai.fields.poorByField.name),
    '',
  );

  p(
    '## 9. Limitations',
    '',
    '- Development-set results only; accuracy on unseen layouts, other issuers or real scans is unknown.',
    '- The address repair vocabulary comes from public place names and from words in the clean sample documents; other vocabulary cannot be repaired.',
    '- Names on poor scans are not repaired (no name lexicon), so they are right only when the scan happens to be clean; their confidence is held below 0.80.',
    '- A house or flat number that contains a letter suffix (for example `22B`) would be read as digits and goes to review with a repair flag.',
    '- No LLM figures: the LLM path is implemented and unit-tested against a fake client, and untested against a live model.',
    '- The officer correction rate needs officer feedback that does not exist yet.',
    '',
  );
  return lines.join('\n') + '\n';
}

export function renderModelCard(e: Evidence): string {
  const ai = e.sample.ai.metrics;
  return [
    '# Model card - OnboardIQ document extraction ("ai" provider)',
    '',
    '## Purpose',
    '',
    'Reads the OCR text of one KYC document and proposes (a) a document type and (b) the fields that belong to it, each with a confidence between 0 and 1. It is an input to the rules engine and never decides: it cannot approve, reject or recommend anything. Humans (officer, then a different checker) approve every reviewed or high-risk case.',
    '',
    '## Versions recorded with every extraction',
    '',
    `- Provider: AI. Extractor version string: \`${e.extractorVersion}\` = provider | rules version | model | prompt version.`,
    '- Rules version 2.0.0 (deterministic parsing, OCR repair, validators, confidence). Model: none by default. Prompt version (only when an LLM is enabled): `extract-v1`.',
    `- Rules engine used for decisions: ${e.rulesEngineVersion}.`,
    '',
    '## How it works',
    '',
    '1. **Injection guard.** Lines that address a reader with instructions (for example "ignore all previous instructions", "approve this applicant") are removed; a document containing any is flagged and classified OTHER with no fields. Such text is not sent to a model.',
    '2. **Classification** from the text only (`declared_doc_type` is never an input): weighted features per type that tolerate OCR damage; too little evidence gives OTHER.',
    '3. **Field extraction** per type with regular expressions and layout rules, OCR repair where the field structure says which characters belong (PAN `AAAAA9999A`, dates, pincode, Aadhaar last 4), and vocabulary repair for addresses. Output is normalised: dates `YYYY-MM-DD`, PAN upper case, Aadhaar last four digits only.',
    '4. **Deterministic validators** reject malformed values (invalid PAN, impossible date, wrong pincode); an invalid value is dropped, not passed on.',
    '5. **Confidence**: 0.97 for a structured field that validated untouched, 0.95 for free text on a clean scan, 0.90 / 0.72 on a garbled scan, 0.70 when any repair was needed. Below 0.80 the rules send the case to review.',
    '6. **Optional LLM (off by default).** Receives only the document text, between random delimiter lines, with an instruction to treat it as untrusted data. It must return structured JSON that matches a strict schema (any extra key, such as a decision, invalidates the answer). Its values are re-validated and merged: agreement raises confidence, disagreement lowers it below 0.80, and it can never change a document type.',
    '7. **Timeout and fallback.** 10 seconds per document. On any failure (error, timeout, malformed answer) the document is OTHER with confidence 0, which routes the case to REVIEW.',
    '',
    '## Measured performance (development set only)',
    '',
    `On the 178 sample documents: classification ${pct(ai.classification.overall)}; field exact-match ${pct(ai.fields.overall)} overall, ${pct(ai.fields.clean)} on clean scans, ${pct(ai.fields.poor)} on poor scans; precision of fields accepted at confidence >= 0.80 ${pct(ai.confidence.accepted)} with ${pct(ai.confidence.coverage)} coverage.`,
    'These figures come from documents the extractor was developed on. Full tables, the confusion matrix and the comparison with the regex-only first version are in `evaluation_report.md`. No figure involves an LLM.',
    '',
    '## Data',
    '',
    '- Development data: the supplied sample texts and truth file (synthetic). The truth is used only to score.',
    '- Address vocabulary: public place names plus words seen in the clean sample documents.',
    '- Evaluation data: no labels; used for agreement checks and to produce outputs only.',
    '',
    '## Responsible AI',
    '',
    '- **Human oversight:** extraction feeds rules; every REVIEW and HIGH-risk case needs a maker and a different checker; officers can override any field with a reason (stored as labelled feedback).',
    '- **Uncertainty:** fields below 0.80 are not used by identity rules and send the case to review, so a misread cannot cause an automatic rejection.',
    '- **Prompt injection:** document text is data. It is screened, delimited, and never obeyed; the injection document in the evaluation set is classified OTHER and cannot change a decision.',
    '- **Privacy:** synthetic data only. No LLM is called unless explicitly enabled (Groq or Anthropic); when enabled only the document text is sent, prompts are not logged, and the provider and model are recorded in the extractor version. Aadhaar: only the last four digits are ever produced.',
    '- **Fairness:** one name normalisation for everyone; the share of NAME_MISMATCH_MINOR by gender is reported in the evaluation report.',
    '- **Governance:** the extractor version is stored with every extraction so results can be reproduced.',
    '',
    '## AI-5 reviewer summary (optional, off by default)',
    '',
    '- Enabled with `REVIEW_SUMMARY_LLM=groq` (`GROQ_API_KEY`, `GROQ_MODEL`) or `anthropic` (`ANTHROPIC_API_KEY`, `EXTRACTION_LLM_MODEL`); prompt version `review-summary-v1`. The provider and model are returned with every summary.',
    '- Input: a fact list built by code from the rule trace and the extracted values of a REVIEW case (no document text, no decision, no rule outcomes), between random delimiter lines, declared untrusted.',
    '- Output: one string through a strict tool schema. Withheld (HTTP 502, nothing shown) when it exceeds 80 words, contains decision or advice wording, or quotes a number or identifier that is not in the case data. Shown labelled "AI-generated" with the model and prompt version; generated only when an officer asks.',
    '- Not evaluated with a live model in this submission: the guardrails are tested with a fake model.',
    '',
    '## Limitations and risks',
    '',
    '- Unknown accuracy outside the development layouts; real scans and other issuers are not covered.',
    '- Names on poor scans can be wrong and are held below 0.80; a wrong value that scores above 0.80 would be accepted (none occurred on the sample).',
    '- The LLM path is not measured here.',
    '',
    '## Out of scope',
    '',
    'Real OCR of images, face matching, real identity or sanctions systems.',
    '',
  ].join('\n');
}

function example9Paragraph(
  x: Evidence['sample']['example9'],
  nameOnPoor: Ratio | undefined,
): string[] {
  if (!x) return [''];
  const low =
    x.fieldsBelowThreshold
      .map((f) => `${f.docType}.${f.field} (${f.confidence.toFixed(2)})`)
      .join(', ') || 'none';
  const becameApprove = x.aiDecision === 'APPROVE';
  return [
    '### Worked example 9 (A2000009, poor PAN scan)',
    '',
    `The spec expects that an AI extractor reading the PAN with confidence >= 0.80 gives APPROVE. Measured: the AI provider reads the PAN as \`${x.panValue ?? 'nothing'}\` at confidence ${x.panConfidence === null ? 'n/a' : x.panConfidence.toFixed(2)}, and the decision is **${x.aiDecision}**${x.aiReasonCodes.length ? ` (${x.aiReasonCodes.join('|')})` : ''}.`,
    becameApprove
      ? 'The case therefore becomes APPROVE, as the spec describes.'
      : `The case does **not** become APPROVE because other required fields on the garbled scans stay below the 0.80 threshold: ${low}. This is a deliberate calibration choice: names on poor scans were right in only ${nameOnPoor ? pct(nameOnPoor) : 'n/a'} of the sample documents and cannot be verified structurally, so they are sent to a person rather than risk an automatic name rejection. Relaxing it would raise the share of approved example-9-style cases and lower the precision of accepted fields.`,
    '',
  ];
}
